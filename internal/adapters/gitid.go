// owns only the managed block at the end of ~/.gitconfig, never touches anything outside it
type GitIdentity struct{}

const (
	BlockBegin = "# >>> cream managed block (do not edit; run `cream rule`) >>>"
	BlockEnd   = "# <<< cream managed block <<<"
)

func (GitIdentity) ID() string { return "git" }

func (GitIdentity) Name() string { return "Git identity" }

func GlobalGitConfig(env *adapter.Env) string {
	if p := env.Env("GIT_CONFIG_GLOBAL"); p != "" {
		return p
	}
	return env.Paths.InHome(".gitconfig")
}

func profileGitFile(env *adapter.Env, profile string) string {
	return filepath.Join(env.Paths.GitDir(), profile+".gitconfig")
}

func (GitIdentity) Files(env *adapter.Env) []string { return []string{GlobalGitConfig(env)} }

func gitQuote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}

func slash(p string) string { return filepath.ToSlash(p) }

func RuleConditions(r config.Rule, goos string) []string {
	switch r.Kind {
	case "dir":
		p := slash(r.Pattern)
		if goos == "windows" {
			// ToSlash only converts on a windows host, but the rule targets goos
			p = strings.ReplaceAll(p, `\`, "/")
		}
		if !strings.HasSuffix(p, "/") {
			p += "/"
		}
		kw := "gitdir"
		if goos == "windows" || goos == "darwin" {
			kw = "gitdir/i" // case insensitive filesystems
		}
		return []string{kw + ":" + p}
	case "remote":
		h := r.Pattern
		// * never crosses / in hasconfig globs so every url shape needs its own pattern (git 2.36+)
		return []string{
			"hasconfig:remote.*.url:https://" + h + "/**",
			"hasconfig:remote.*.url:https://*@" + h + "/**",
			"hasconfig:remote.*.url:ssh://*@" + h + "/**",
			"hasconfig:remote.*.url:ssh://*@" + h + ":*/**",
			"hasconfig:remote.*.url:*@" + h + ":*/**", // git@host:group/repo
			"hasconfig:remote.*.url:*@" + h + ":*",    // git@host:repo
		}
	}
	return nil
}

// fallback is the identity outside any rule, nil in strict mode
func RenderBlock(env *adapter.Env, cfg *config.Config, fallback *config.Profile) string {
	var b strings.Builder
	b.WriteString(BlockBegin + "\n")
	b.WriteString("[user]\n\tuseConfigOnly = true\n")
	if fallback != nil && !fallback.Git.IsZero() {
		if fallback.Git.Name != "" {
			b.WriteString("\tname = " + gitQuote(fallback.Git.Name) + "\n")
		}
		if fallback.Git.Email != "" {
			b.WriteString("\temail = " + gitQuote(fallback.Git.Email) + "\n")
		}
	}
	for _, name := range cfg.Names() {
		p := cfg.Profiles[name]
		if p.Git.IsZero() {
			continue
		}
		for _, r := range p.Rules {
			for _, cond := range RuleConditions(r, env.OS()) {
				fmt.Fprintf(&b, "[includeIf %s]\n\tpath = %s\n", gitQuote(cond), gitQuote(slash(profileGitFile(env, name))))
			}
		}
	}
	b.WriteString(BlockEnd + "\n")
	return b.String()
}

func RenderProfileInclude(p *config.Profile) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by CRE.A.M for profile %q. Do not edit.\n[user]\n", p.Name)
	if p.Git.Name != "" {
		b.WriteString("\tname = " + gitQuote(p.Git.Name) + "\n")
	}
	if p.Git.Email != "" {
		b.WriteString("\temail = " + gitQuote(p.Git.Email) + "\n")
	}
	if p.Git.SigningKey != "" {
		b.WriteString("\tsigningkey = " + gitQuote(p.Git.SigningKey) + "\n")
	}
	return b.String()
}

func splitBlock(content string) (outside string, block string) {
	start := strings.Index(content, BlockBegin)
	if start < 0 {
		return content, ""
	}
	end := strings.Index(content[start:], BlockEnd)
	if end < 0 {
		return content[:start], content[start:]
	}
	end += start + len(BlockEnd)
	if end < len(content) && content[end] == '\n' {
		end++
	}
	return content[:start] + content[end:], content[start:end]
}

// the block goes last so its includes win over earlier settings
func ReplaceBlock(content, block string) string {
	outside, _ := splitBlock(content)
	outside = strings.TrimRight(outside, "\n")
	if outside != "" {
		outside += "\n\n"
	}
	return outside + block
}

var userEmailOutside = regexp.MustCompile(`(?ims)^\s*\[user\][^\[]*?^\s*email\s*=`)

// a user.email outside the block defeats strict mode
func HasGlobalEmailOutsideBlock(content string) bool {
	outside, _ := splitBlock(content)
	return userEmailOutside.MatchString(outside)
}

func (g GitIdentity) Status(ctx context.Context, env *adapter.Env) adapter.Status {
	var s adapter.Status
	if _, err := env.Run.LookPath("git"); err == nil {
		s.Installed = true
	}
	content, _, err := fsutil.ReadFileIfExists(GlobalGitConfig(env))
	if err != nil {
		s.Warning = err.Error()
	}
	_, block := splitBlock(string(content))
	if s.Installed {
		out, err := env.Run.Run(ctx, nil, nil, "git", "config", "--get", "user.email")
		if err == nil && strings.TrimSpace(string(out)) != "" {
			s.LoggedIn = true
			s.Account = strings.TrimSpace(string(out))
		}
	}
	if block == "" {
		s.Detail = "no managed block yet"
	} else {
		s.Detail = fmt.Sprintf("%d includeIf rule(s) managed", strings.Count(block, "[includeIf"))
	}
	if env.Config != nil && env.Config.GitStrict() && hasAnyRule(env.Config) && HasGlobalEmailOutsideBlock(string(content)) {
		s.Warning = "a global user.email outside the cream block defeats strict mode"
	}
	return s
}

func (g GitIdentity) Import(ctx context.Context, env *adapter.Env, p *config.Profile) (*config.Account, error) {
	get := func(key string) string {
		out, err := env.Run.Run(ctx, nil, nil, "git", "config", "--global", "--get", key)
		if err != nil {
			return ""
		}
		return strings.TrimSpace(string(out))
	}
	if p.Git.IsZero() {
		p.Git.Name = get("user.name")
		p.Git.Email = get("user.email")
		if p.Git.SigningKey == "" {
			p.Git.SigningKey = get("user.signingkey")
		}
	}
	if p.Git.Email == "" {
		return nil, errors.New("no git identity (set one with `cream profile set " + p.Name + " --git-name … --git-email …`)")
	}
	return &config.Account{Label: p.Git.Email, Imported: time.Now().UTC().Truncate(time.Second)}, nil
}

func (g GitIdentity) Activate(ctx context.Context, env *adapter.Env, p *config.Profile, dryRun bool) ([]adapter.Change, error) {
	if env.Config == nil {
		return nil, errors.New("git: no config")
	}
	if p.Git.IsZero() {
		return nil, adapter.ErrNotImported{Adapter: g.ID(), Profile: p.Name}
	}
	return Sync(env, env.Config, Fallback(env.Config, p), dryRun)
}

// with no rules the active profile is the global identity, strict only kicks in once rules exist
func Fallback(cfg *config.Config, active *config.Profile) *config.Profile {
	if !cfg.GitStrict() || !hasAnyRule(cfg) {
		return active
	}
	return nil
}

func hasAnyRule(cfg *config.Config) bool {
	for _, p := range cfg.Profiles {
		if len(p.Rules) > 0 {
			return true
		}
	}
	return false
}

// locked profiles lose their rules and can't be the fallback, with everything locked no identity is left
func unlockedView(cfg *config.Config, fallback *config.Profile) (*config.Config, *config.Profile) {
	if !cfg.AnyLocked() {
		return cfg, fallback
	}
	view := *cfg
	view.Profiles = map[string]*config.Profile{}
	for name, p := range cfg.Profiles {
		if !cfg.Locked(name) {
			view.Profiles[name] = p
		}
	}
	if fallback != nil && cfg.Locked(fallback.Name) {
		fallback = nil
	}
	return &view, fallback
}

func Sync(env *adapter.Env, cfg *config.Config, fallback *config.Profile, dryRun bool) ([]adapter.Change, error) {
	cfg, fallback = unlockedView(cfg, fallback)
	var changes []adapter.Change
	for _, name := range cfg.Names() {
		p := cfg.Profiles[name]
		if p.Git.IsZero() {
			continue
		}
		path := profileGitFile(env, name)
		want := RenderProfileInclude(p)
		if cur, _, _ := fsutil.ReadFileIfExists(path); string(cur) != want {
			changes = append(changes, adapter.Change{Adapter: "git", Kind: "file", Target: path, Action: "write"})
			if !dryRun {
				if err := fsutil.WriteFileAtomic(path, []byte(want), 0o600); err != nil {
					return nil, err
				}
			}
		}
	}
	gc := GlobalGitConfig(env)
	cur, _, err := fsutil.ReadFileIfExists(gc)
	if err != nil {
		return nil, err
	}
	next := ReplaceBlock(string(cur), RenderBlock(env, cfg, fallback))
	if next != string(cur) {
		changes = append(changes, adapter.Change{Adapter: "git", Kind: "gitconfig", Target: gc + " (managed block)", Action: "patch"})
		if !dryRun {
			if err := fsutil.WriteFileAtomic(gc, []byte(next), 0o644); err != nil {
				return nil, err
			}
		}
	}
	return changes, nil
}

// identity follows the repo, not the session
func (GitIdentity) SessionEnv(ctx context.Context, env *adapter.Env, p *config.Profile) ([]string, func() error, error) {
	return nil, nil, nil
}

func (g GitIdentity) Verify(ctx context.Context, env *adapter.Env) (string, error) {
	out, err := env.Run.Run(ctx, nil, nil, "git", "config", "--get", "user.email")
	if err != nil {
		return "", errors.New("no identity applies in the current directory (no rule matches)")
	}
	return strings.TrimSpace(string(out)), nil
}

// order here is the display order
func All() []adapter.Adapter {
	return []adapter.Adapter{Claude{}, Codex{}, GitHub{}, GitLab{}, GitIdentity{}}
}

func IDs() []string {
	var out []string
	for _, a := range All() {
		out = append(out, a.ID())
	}
	return out
}
